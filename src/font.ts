// Parsed glyph: array of strokes, each stroke an array of [x, y] points.
export type Glyph = [number, number][][];

const CACHE = new Map<string, Glyph>();

export function glyphFor(ch: string): Glyph | null {
  let g = CACHE.get(ch);
  if (g) return g;
  const raw = GLYPHS[ch];
  if (raw === undefined) return null;
  g = raw.split('|').map((stroke) =>
    stroke.trim().split(/\s+/).map((pt) => {
      const [x, y] = pt.split(',').map(Number);
      return [x, y] as [number, number];
    }),
  );
  CACHE.set(ch, g);
  return g;
}

/** Advance width of one character in font units (grid is 7 wide). */
export function charAdvance(ch: string): number {
  if (ch === ' ') return 3.2;
  if (ch === '—' || ch === '–') return 8;
  if (ch === 'i' || ch === 'l' || ch === 'j' || ch === '!' || ch === ':' || ch === ';' || ch === '.' || ch === ',' || ch === "'" || ch === '’' || ch === '‘' || ch === '·' || ch === '|') return 4.2;
  if (ch === 'm' || ch === 'w' || ch === 'M' || ch === 'W' || ch === '%') return 7.6;
  return 6.6;
}

/** Width of a string at the given scale (font size in px, cap height ~ size). */
export function textWidth(text: string, size: number): number {
  const unit = size / 10; // grid height 10 = cap height
  let w = 0;
  for (const ch of text) w += charAdvance(ch) * unit;
  return w;
}
